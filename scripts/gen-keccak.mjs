// Generates packages/latticework/src/keccak-f1600.ts: Keccak-f[1600] with
// every step unrolled into straight-line code on local variables.
//
//   node scripts/gen-keccak.mjs
//
// The readable version, with loops and tables, is keccakF1600Reference in
// keccak.ts. They compute the same thing; a test checks that on random
// states. This one exists because the KEM spends most of its time in
// Keccak, and V8 does much better with 50 named locals than with indexed
// loops over typed arrays.
import { writeFileSync } from 'node:fs';

// Rotation offsets, generated the same way as in keccak.ts (FIPS 202 Alg. 2).
const rho = Array(25).fill(0);
{
  let x = 1;
  let y = 0;
  for (let t = 0; t < 24; t++) {
    rho[x + 5 * y] = (((t + 1) * (t + 2)) / 2) % 64;
    [x, y] = [y, (2 * x + 3 * y) % 5];
  }
}

const L = [];
const emit = (s) => L.push(s);

emit('// Generated by scripts/gen-keccak.mjs. Do not edit by hand.');
emit('//');
emit('// Keccak-f[1600], unrolled. Lane i of the state is s[2i] (low 32 bits) and');
emit('// s[2i + 1] (high 32 bits). See keccakF1600Reference in keccak.ts for the');
emit('// same permutation written with loops.');
emit('');
emit("import { ROUND_CONSTANTS as RC } from './keccak-constants.ts';");
emit('');
emit('export function keccakF1600(s: Uint32Array): void {');
for (let i = 0; i < 50; i++) emit(`  let a${i} = s[${i}]!;`);
emit('  for (let round = 0; round < 48; round += 2) {');
emit('    // theta');
for (let x = 0; x < 5; x++) {
  const lo = [0, 1, 2, 3, 4].map((y) => `a${2 * (x + 5 * y)}`).join(' ^ ');
  const hi = [0, 1, 2, 3, 4].map((y) => `a${2 * (x + 5 * y) + 1}`).join(' ^ ');
  emit(`    const c${x}l = ${lo};`);
  emit(`    const c${x}h = ${hi};`);
}
for (let x = 0; x < 5; x++) {
  const p = (x + 4) % 5;
  const n = (x + 1) % 5;
  emit(`    const d${x}l = c${p}l ^ ((c${n}l << 1) | (c${n}h >>> 31));`);
  emit(`    const d${x}h = c${p}h ^ ((c${n}h << 1) | (c${n}l >>> 31));`);
}
emit('    // theta applied, then rho (rotate) and pi (move lane (x, y) to (y, 2x + 3y))');
for (let x = 0; x < 5; x++) {
  for (let y = 0; y < 5; y++) {
    const src = x + 5 * y;
    const dest = y + 5 * ((2 * x + 3 * y) % 5);
    const n = rho[src];
    const lo = `(a${2 * src} ^ d${x}l)`;
    const hi = `(a${2 * src + 1} ^ d${x}h)`;
    emit(`    const t${src}l = ${lo};`);
    emit(`    const t${src}h = ${hi};`);
    let bl;
    let bh;
    if (n === 0) {
      bl = `t${src}l`;
      bh = `t${src}h`;
    } else if (n < 32) {
      bl = `(t${src}l << ${n}) | (t${src}h >>> ${32 - n})`;
      bh = `(t${src}h << ${n}) | (t${src}l >>> ${32 - n})`;
    } else if (n === 32) {
      bl = `t${src}h`;
      bh = `t${src}l`;
    } else {
      const m = n - 32;
      bl = `(t${src}h << ${m}) | (t${src}l >>> ${32 - m})`;
      bh = `(t${src}l << ${m}) | (t${src}h >>> ${32 - m})`;
    }
    emit(`    const b${dest}l = ${bl};`);
    emit(`    const b${dest}h = ${bh};`);
  }
}
emit('    // chi');
for (let y = 0; y < 5; y++) {
  for (let x = 0; x < 5; x++) {
    const i = x + 5 * y;
    const i1 = ((x + 1) % 5) + 5 * y;
    const i2 = ((x + 2) % 5) + 5 * y;
    emit(`    a${2 * i} = b${i}l ^ (~b${i1}l & b${i2}l);`);
    emit(`    a${2 * i + 1} = b${i}h ^ (~b${i1}h & b${i2}h);`);
  }
}
emit('    // iota');
emit('    a0 ^= RC[round]!;');
emit('    a1 ^= RC[round + 1]!;');
emit('  }');
for (let i = 0; i < 50; i++) emit(`  s[${i}] = a${i};`);
emit('}');
emit('');

const out = new URL('../packages/latticework/src/keccak-f1600.ts', import.meta.url);
writeFileSync(out, L.join('\n'));
console.log(`wrote ${out.pathname} (${L.length} lines)`);
